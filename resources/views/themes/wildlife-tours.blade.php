					<h3>Wildlife Tour Packages</h3>
<p>
	Adventure seems synonymous to wildlife tour especially when it comes to jungle safari, camping under the stars in forests, bonfire along the riverside and much more. The wildlife in India is as diverse as its people and culture. From the rainy jungles of Periyar to dry forests of Ranthambore, the country is home to the big cats, Royal Bengal Tiger, Leopard, Asiatic Lion, Asiatic Elephant, the Indian Wolf, foxes, wild crocodiles, species of deer and antelope, Indian wild dog (Dhole), monkeys, reptiles, rhinoceros, the Indian Bison and a countless variety of birds. Catering the interest of adventure seekers to an avid bird watcher, the flora and fauna of the country entice a big number of tourists visiting India from all over the world while choosing the wildlife tour to India.</p>
 


  
 <span id="text"><p>
